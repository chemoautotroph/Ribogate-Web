"""Maintainer utility: lock the installed distribution versions and PyPI artifacts."""
import hashlib
import importlib.metadata
import json
from pathlib import Path
import urllib.request

ROOT = Path(__file__).resolve().parents[1]


def main():
    # Includes transitive runtime dependencies, plus the pinned build toolchain.
    distributions = sorted(importlib.metadata.distributions(), key=lambda item:item.metadata['Name'].lower())
    lines = ['# Windows x64 / CPython 3.9.19; generated by scripts/lock_requirements.py',
             '# PyPI artifact SHA-256 hashes. Install with --require-hashes --no-build-isolation.']
    bootstrap = ['# Pinned, hash-verified build toolchain.']
    for dist in distributions:
        name, version = dist.metadata['Name'], dist.version
        url = f'https://pypi.org/pypi/{name}/{version}/json'
        with urllib.request.urlopen(url, timeout=30) as response:
            release = json.load(response)
        hashes = sorted({item['digests']['sha256'] for item in release['urls'] if not item['yanked']})
        if not hashes:
            raise RuntimeError('No published artifacts for ' + name + '==' + version)
        block = [name + '==' + version + ' \\']
        block.extend('    --hash=sha256:' + digest + (' \\' if i < len(hashes)-1 else '')
                     for i,digest in enumerate(hashes))
        lines.extend(block)
        if name.lower() in ('pip', 'setuptools', 'wheel'):
            bootstrap.extend(block)
    path = ROOT / 'requirements.lock'
    path.write_bytes(('\n'.join(lines)+'\n').encode('utf-8'))
    (ROOT / 'requirements-bootstrap.lock').write_bytes(('\n'.join(bootstrap)+'\n').encode('utf-8'))
    print('Locked', len(distributions), 'distributions;', hashlib.sha256(path.read_bytes()).hexdigest())


if __name__ == '__main__':
    main()
